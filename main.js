function formatUserContent(text, attachments) {
  if (attachments.length === 0) {
    return text;
  }
  const blocks = attachments.map((note) => {
    return `### ${note.path}
${truncate(note.content, MAX_ATTACH_CHARS)}`;
  });
  return `${text}

Attached notes:

${blocks.join("\n\n")}`;
}

function mentionQuery(value, cursor) {
  const before = value.slice(0, cursor);
  const at = before.lastIndexOf("@");
  if (at < 0) {
    return null;
  }
  if (at > 0) {
    const prev = before[at - 1];
    if (prev && !/\s/.test(prev)) {
      return null;
    }
  }
  const query = before.slice(at + 1);
  if (query.includes("\n") || query.includes(" ")) {
    return null;
  }
  return { start: at, query };
}
function suggestNotes(app, query, limit = 12) {
  const files = app.vault.getMarkdownFiles();
  const needle = query.toLowerCase();
  const scored = files.map((file) => ({ file, score: scoreFile(file, needle) })).filter((row) => row.score > 0 || needle.length === 0).sort((a, b) => b.score - a.score || a.file.path.localeCompare(b.file.path));
  return scored.slice(0, limit).map((row) => row.file);
}
function scoreFile(file, needle) {
  if (!needle) {
    return 1;
  }
  const path = file.path.toLowerCase();
  const name = file.basename.toLowerCase();
  if (name === needle) {
    return 100;
  }
  if (name.startsWith(needle)) {
    return 80;
  }
  if (name.includes(needle)) {
    return 60;
  }
  if (path.includes(needle)) {
    return 40;
  }
  return 0;
}

